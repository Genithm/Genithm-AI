"use client";

import {useState} from "react";
import {
 MAX_SALMON_SAMPLES,MAX_SALMON_QUANT_BYTES,
 inspectSalmonQuantifications,type SalmonMatrix
} from "@/lib/salmon-quant-matrix";

type SelectedQuant={id:number;file:File;sample:string};
function safeDefault(file:File,index:number){
  const label=file.webkitRelativePath||file.name;
  const byDirectory=label.includes("/")?label.split("/").at(-2):null;
  return (byDirectory||file.name.replace(/(?:\.quant)?\.sf$/i,"")||"S"+(index+1))
    .replace(/[^A-Za-z0-9_.-]/g,"_").slice(0,64);
}
function save(content:string,filename:string){
  const url=URL.createObjectURL(new Blob([content],{type:"text/tab-separated-values;charset=utf-8"}));
  const link=document.createElement("a");link.href=url;link.download=filename;
  document.body.append(link);link.click();link.remove();
  setTimeout(()=>URL.revokeObjectURL(url),1000);
}
export function SalmonQuantWorkbench(){
  const [selection,setSelection]=useState<SelectedQuant[]>([]);
  const [result,setResult]=useState<SalmonMatrix|null>(null);
  const [error,setError]=useState("");
  const [busy,setBusy]=useState(false);
  function pick(files:FileList|null){
    if(!files)return;
    const list=Array.from(files);
    if(list.length>MAX_SALMON_SAMPLES){
      setError("At most 24 quant.sf files may be compared.");setResult(null);return;
    }
    setSelection(list.map((file,index)=>({id:index,file,sample:safeDefault(file,index)})));
    setResult(null);setError("");
  }
  async function inspect(){
    if(busy||selection.length===0)return;
    setBusy(true);setError("");setResult(null);
    try{
      if(selection.some(s=>s.file.size<1||s.file.size>MAX_SALMON_QUANT_BYTES))
        throw new Error("Each Salmon quant.sf file must be nonempty and at most 24 MiB.");
      const inputs=await Promise.all(selection.map(async item=>({
        sample:item.sample,text:await item.file.text()
      })));
      setResult(inspectSalmonQuantifications(inputs));
    }catch(e){setError(e instanceof Error?e.message:"Could not validate Salmon quantification files.");}
    finally{setBusy(false);}
  }
  return <section className="genithm-card" aria-label="Salmon output analysis" style={{marginTop:22}}>
    <div className="genithm-page-kicker">PHASE 1 / EXISTING QUANTIFICATION OUTPUTS</div>
    <h2>Import real Salmon transcript estimates</h2>
    <p>Select one to 24 existing Salmon quant.sf files. Genithm reads the files <strong>only in your browser</strong>, validates the reported TPM/estimated-fragment totals and joins transcript identities into a genuine measured matrix.</p>
    <p className="genithm-note">Salmon must already have been run independently. This importer does not map FASTQ reads, build indexes, prove reference identity, infer raw gene counts or run differential expression.</p>
    <label htmlFor="salmon-quant-files"><strong>Choose quant.sf files</strong></label>
    <input id="salmon-quant-files" aria-label="Select Salmon quant.sf output files" type="file" accept=".sf,.tsv,text/plain" multiple onChange={e=>pick(e.currentTarget.files)} />
    {selection.length>0&&<div style={{marginTop:12}}>
      <h3>Assign one unique biological sample ID per file</h3>
      <p className="genithm-note">If several files are named quant.sf, assign IDs manually. Technical lanes should already be consolidated by the Salmon workflow.</p>
      {selection.map(item=><div key={item.id} style={{display:"flex",alignItems:"center",gap:10,flexWrap:"wrap",marginTop:7}}>
        <label htmlFor={"salmon-id-"+item.id}>Sample for {item.file.name}:</label>
        <input id={"salmon-id-"+item.id} value={item.sample} maxLength={64}
          onChange={e=>{setSelection(old=>old.map(v=>v.id===item.id?{...v,sample:e.target.value}:v));setResult(null);setError("");}}/>
        <span className="genithm-note">{(item.file.size/(1024*1024)).toFixed(2)} MiB</span>
      </div>)}
    </div>}
    <div style={{marginTop:14}}>
      <button type="button" className="button" onClick={()=>void inspect()} disabled={busy||!selection.length}>
        {busy?"Validating transcript matrices…":"Analyze existing Salmon outputs"}
      </button>
    </div>
    {error&&<p className="error" role="alert">{error}</p>}
    {result&&<div role="status" style={{marginTop:18}}>
      <h3>Real transcript-level output imported (not generated by Genithm)</h3>
      <p><strong>{result.samples}</strong> samples · <strong>{result.transcripts.toLocaleString()}</strong> matched transcripts. All reported TPM and estimated-fragment values come from the selected local files.</p>
      <table style={{width:"100%",textAlign:"left"}}>
        <thead><tr><th>Sample</th><th>Reported TPM total</th><th>Estimated fragments</th><th>Expressed transcripts</th></tr></thead>
        <tbody>{result.sample_stats.map(item=><tr key={item.sample}>
          <td>{item.sample}</td><td>{item.total_reported_tpm.toLocaleString()}</td>
          <td>{item.total_estimated_fragments.toLocaleString()}</td>
          <td>{item.expressed_transcripts.toLocaleString()}</td>
        </tr>)}</tbody>
      </table>
      <div style={{display:"flex",gap:8,flexWrap:"wrap",marginTop:12}}>
        <button type="button" className="button" onClick={()=>save(result.transcript_tpm_tsv,"genithm-transcript-TPM.tsv")}>Download TPM matrix</button>
        <button type="button" className="button" onClick={()=>save(result.transcript_estimated_fragments_tsv,"genithm-transcript-ESTIMATED-fragments.tsv")}>Download estimated counts</button>
        <button type="button" className="button" onClick={()=>save(result.summary_tsv,"genithm-salmon-summary.tsv")}>Download sample QC</button>
      </div>
      <h4>Scientific limitations</h4>
      <ul>{result.warnings.map((w,i)=><li key={i}>{w}</li>)}</ul>
    </div>}
  </section>;
}
